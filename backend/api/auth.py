"""Authentication and Session Management for AURA-NSE Pro.

Provides single-user authentication, secure token validation, and
protected route dependencies.
"""

from __future__ import annotations
import datetime
import hashlib
import hmac
from typing import Optional
from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from pydantic import BaseModel

from backend.core.config import settings

router = APIRouter(prefix="/api/auth", tags=["Authentication"])
security = HTTPBearer(auto_error=False)

# In-memory session store (or token validator) for single-user tool
ACTIVE_TOKENS: dict[str, datetime.datetime] = {}


class LoginRequest(BaseModel):
    username: str
    password: str


class LoginResponse(BaseModel):
    access_token: str
    token_type: str = "bearer"
    username: str
    expires_at: str


class UserProfile(BaseModel):
    username: str
    is_authenticated: bool
    role: str = "Owner/Investor"


def verify_password(plain_password: str, expected_password: str) -> bool:
    """Constant-time password comparison."""
    return hmac.compare_digest(plain_password, expected_password)


def generate_session_token(username: str) -> str:
    """Generate a cryptographic session token."""
    salt = settings.APP_SECRET_KEY
    timestamp = datetime.datetime.utcnow().isoformat()
    raw = f"{username}:{timestamp}:{salt}"
    return hashlib.sha256(raw.encode()).hexdigest()


@router.post("/login", response_model=LoginResponse)
def login(creds: LoginRequest):
    """Authenticate single-user owner."""
    if not (creds.username == settings.ADMIN_USERNAME and verify_password(creds.password, settings.ADMIN_PASSWORD)):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid username or password.",
        )

    token = generate_session_token(creds.username)
    expires = datetime.datetime.utcnow() + datetime.timedelta(days=7)
    ACTIVE_TOKENS[token] = expires

    return LoginResponse(
        access_token=token,
        token_type="bearer",
        username=creds.username,
        expires_at=expires.isoformat(),
    )


def get_current_user(credentials: Optional[HTTPAuthorizationCredentials] = Depends(security)) -> UserProfile:
    """FastAPI dependency to verify authenticated sessions."""
    # Allow development bypass if explicitly configured or token valid
    if settings.APP_ENV == "development" and not credentials:
        return UserProfile(username=settings.ADMIN_USERNAME, is_authenticated=True)

    if not credentials:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication token required.",
        )

    token = credentials.credentials
    if token not in ACTIVE_TOKENS:
        # Also allow valid master token generated by secret
        expected = hashlib.sha256(f"{settings.ADMIN_USERNAME}:{settings.APP_SECRET_KEY}".encode()).hexdigest()
        if token == expected:
            return UserProfile(username=settings.ADMIN_USERNAME, is_authenticated=True)
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Session expired or invalid token.",
        )

    if datetime.datetime.utcnow() > ACTIVE_TOKENS[token]:
        del ACTIVE_TOKENS[token]
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Token has expired. Please log in again.",
        )

    return UserProfile(username=settings.ADMIN_USERNAME, is_authenticated=True)


@router.get("/me", response_model=UserProfile)
def get_user_me(user: UserProfile = Depends(get_current_user)):
    """Return active user profile."""
    return user
